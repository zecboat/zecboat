import { defineConfig } from "vite";
import { sveltekit } from "@sveltejs/kit/vite";

// `@ts-expect-error process is a nodejs global` used to sit here. Installing
// @types/qrcode pulled in @types/node, so `process` is now typed and the
// suppression became an error in its own right — @ts-expect-error fails when
// there is nothing to expect.
const host = process.env.TAURI_DEV_HOST;

// https://vite.dev/config/
export default defineConfig(async () => ({
  plugins: [sveltekit()],

  // Vite options tailored for Tauri development and only applied in `tauri dev` or `tauri build`
  //
  // 1. prevent Vite from obscuring rust errors
  clearScreen: false,
  // 2. tauri expects a fixed port, fail if that port is not available
  server: {
    port: 1420,
    strictPort: true,
    host: host || "127.0.0.1",
    hmr: host
      ? {
          protocol: "ws",
          host,
          port: 1421,
        }
      : undefined,
    watch: {
      // 3. tell Vite to ignore watching `src-tauri`
      ignored: ["**/src-tauri/**"],
    },
  },
}));
